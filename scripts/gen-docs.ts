const HEADER = "<!-- Generated by `npm run docs` from the source code. Do not edit by hand. -->\n\n";
const here = path.dirname(fileURLToPath(import.meta.url));
export const REFERENCE_DIR = path.resolve(here, "..", "docs", "reference");

type Schema = {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
  oneOf?: Schema[];
  items?: Schema;
  properties?: Record<string, Schema>;
  additionalProperties?: Schema | boolean;
  required?: string[];
  description?: string;
  default?: unknown;
  minimum?: number;
  maximum?: number;
  exclusiveMinimum?: number;
};

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function typeOf(s: Schema): string {
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.const !== undefined) return JSON.stringify(s.const);
  const alts = s.anyOf ?? s.oneOf;
  if (alts) return alts.map(typeOf).join(" | ");
  if (s.type === "array") return `${s.items ? typeOf(s.items) : "unknown"}[]`;
  if (s.type === "object") {
    if (s.properties) return `{ ${Object.keys(s.properties).join(", ")} }`;
    return "object";
  }
  if (Array.isArray(s.type)) return s.type.join(" | ");
  return s.type ?? "any";
}

function range(s: Schema): string {
  const parts: string[] = [];
  if (s.minimum !== undefined) parts.push(`≥ ${s.minimum}`);
  if (s.exclusiveMinimum !== undefined) parts.push(`> ${s.exclusiveMinimum}`);
  // zod's .int() emits MAX_SAFE_INTEGER as a bound; that's noise in docs.
  if (s.maximum !== undefined && s.maximum < Number.MAX_SAFE_INTEGER) parts.push(`≤ ${s.maximum}`);
  return parts.join(", ");
}

/** Markdown table of an object schema's properties (one level of nesting is expanded). */
function paramTable(schema: Schema): string {
  const props = schema.properties ?? {};
  if (!Object.keys(props).length) return "_No parameters._\n";
  const required = new Set(schema.required ?? []);
  const rows: string[] = ["| Parameter | Type | Required | Default | Description |", "|---|---|---|---|---|"];
  const add = (name: string, p: Schema, req: boolean) => {
    const r = range(p);
    const notes = [p.description, r && `(${r})`].filter(Boolean).join(" ");
    const def = p.default !== undefined ? `\`${JSON.stringify(p.default)}\`` : "";
    rows.push(`| \`${name}\` | ${cell(typeOf(p))} | ${req ? "yes" : ""} | ${cell(def)} | ${cell(notes)} |`);
    if (p.type === "object" && p.properties) {
      const inner = new Set(p.required ?? []);
      for (const [k, v] of Object.entries(p.properties)) add(`${name}.${k}`, v, inner.has(k));
    }
  };
  for (const [name, p] of Object.entries(props)) add(name, p, required.has(name) && p.default === undefined);
  return `${rows.join("\n")}\n`;
}

const jsonSchema = (t: z.ZodType) => z.toJSONSchema(t, { io: "input", unrepresentable: "any" }) as Schema;
/** GitHub heading anchor: lowercase, punctuation other than - and _ dropped, spaces become -. */
const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9 _-]/g, "").replace(/ /g, "-");

function claudeTools(): string {
  const groups: [string, string[]][] = [
    ["Inspect & project", ["get_project", "new_project", "set_project_settings", "undo", "redo"]],
    ["Library", ["list_templates", "get_template", "apply_template", "list_effects", "list_audio_effects", "list_transitions", "list_animations", "list_caption_styles", "list_components"]],
    ["Media & primary track", ["import_media", "add_clip", "update_clip", "remove_clip", "move_clip", "split_clip", "trim_clip", "set_speed", "set_transition", "add_effect", "remove_effect"]],
    ["Retouch", ["retouch"]],
    ["Layers", ["add_text", "add_media_overlay", "add_shape", "add_component", "update_layer", "reorder_layer", "remove_layer"]],
    ["Audio", ["add_audio", "update_audio", "remove_audio", "set_volume", "enhance_audio", "add_audio_effect", "remove_audio_effect"]],
    ["Sound map, beats & moments", ["analyze_audio", "remove_silences", "detect_scenes", "detect_beats", "beat_sync", "add_moment_effect", "list_sound_effects", "add_sound_effect"]],
    ["Transcript & captions", ["transcribe", "set_transcript", "get_transcript", "search_transcript", "find_retakes", "remove_retakes", "cleanup_speech", "cut_ranges", "assemble_from_source", "set_captions", "export_captions"]],
    ["Voice-over", ["generate_voiceover"]],
    ["Color", ["color_adjust", "get_color", "analyze_color", "sample_color", "render_scopes"]],
    ["Preview & render", ["render_frame", "render_contact_sheet", "render_preview", "render_video"]],
  ];
  const grouped = new Set(groups.flatMap(([, names]) => names));
  const missing = TOOLS.filter((t) => !grouped.has(t.name)).map((t) => t.name);
  if (missing.length) groups.push(["Other", missing]);

  let out = `${HEADER}# Claude tools\n\n${TOOLS.length} tools that Claude calls to edit a video. They are defined in [src/claude/tools.ts](../../src/claude/tools.ts) and exposed with \`toAnthropicTools()\` in Messages API format. Run them with \`executeTool(session, name, input)\`. Inputs are validated against the schemas below, and errors come back as \`isError\` results instead of exceptions.\n\nTools marked **edits** change the project, record an undo step and notify the live preview. Tools marked **read-only** only inspect or render.\n\n`;
  out += "## Contents\n\n";
  for (const [group, names] of groups) out += `- **${group}**: ${names.map((n) => `[${n}](#${slug(n)})`).join(", ")}\n`;
  for (const [group, names] of groups) {
    out += `\n## ${group}\n`;
    for (const name of names) {
      const t = TOOLS.find((x) => x.name === name);
      if (!t) continue;
      out += `\n### ${t.name}\n\n${t.mutates ? "**edits**" : "**read-only**"}. ${t.description}\n\n${paramTable(jsonSchema(t.input))}`;
    }
  }
  return out;
}

function effects(): string {
  const cats = [...new Set(EFFECTS.map((e) => e.category))];
  let out = `${HEADER}# Effects\n\n${EFFECTS.length} visual effects. Apply them to a clip (\`clips[].effects\`), a media layer (\`layers[].effects\`), or the whole video (\`project.effects\`). With Claude, use the \`add_effect\` tool and target a clip id, a layer id, or \`"global"\`.\n\n\`\`\`json\n{ "type": "kenBurns", "params": { "zoomTo": 1.2, "pan": "right" } }\n\`\`\`\n\nParameters you omit take their defaults. Each effect compiles to an FFmpeg filter chain ([src/library/effects/index.ts](../../src/library/effects/index.ts)). Register your own with \`registerEffect\`.\n\n## Contents\n\n`;
  for (const c of cats) out += `- **${c}**: ${EFFECTS.filter((e) => e.category === c).map((e) => `[${e.id}](#${slug(e.id)})`).join(", ")}\n`;
  for (const c of cats) {
    out += `\n## ${c[0]!.toUpperCase()}${c.slice(1)}\n`;
    for (const e of EFFECTS.filter((x) => x.category === c)) out += `\n### ${e.id}\n\n**${e.name}**. ${e.description}\n\n${paramTable(jsonSchema(e.params))}`;
  }
  return out;
}

function audioEffects(): string {
  const cats = [...new Set(AUDIO_EFFECTS.map((e) => e.category))];
  let out = `${HEADER}# Audio effects\n\n${AUDIO_EFFECTS.length} audio effects. Apply them to a primary clip (\`clips[].audioEffects\`), an audio clip (\`audio[].audioEffects\`), a media layer (\`layers[].audioEffects\`), or the final mix (\`project.audioEffects\`). With Claude, use \`add_audio_effect\` and target a clip, audio clip or layer id, or \`"master"\`. \`enhance_audio\` sets up a full speech cleanup chain in one call.\n\n\`\`\`json\n{ "type": "denoise", "params": { "amount": 40 } }\n\`\`\`\n\nEffects run in order, after speed and before volume and fades. Parameters you omit take their defaults. Each effect compiles to an FFmpeg audio filter chain ([src/library/audio-effects/index.ts](../../src/library/audio-effects/index.ts)). Register your own with \`registerAudioEffect\`.\n\n## Contents\n\n`;
  for (const c of cats) out += `- **${c}**: ${AUDIO_EFFECTS.filter((e) => e.category === c).map((e) => `[${e.id}](#${slug(e.id)})`).join(", ")}\n`;
  for (const c of cats) {
    out += `\n## ${c[0]!.toUpperCase()}${c.slice(1)}\n`;
    for (const e of AUDIO_EFFECTS.filter((x) => x.category === c)) out += `\n### ${e.id}\n\n**${e.name}**. ${e.description}\n\n${paramTable(jsonSchema(e.params))}`;
  }
  return out;
}

function soundEffects(): string {
  let out = `${HEADER}# Sound effects\n\n${SOUND_EFFECTS.length} sound effects, synthesized by FFmpeg, so no audio files are needed. With Claude, use \`add_sound_effect\` with timeline times (\`align: "end"\` makes a sound finish at the time, for risers), or \`beat_sync\` with \`sound\` to add one on every beat. Each effect is rendered once to a WAV file in the session's output folder and added as an \`sfx\` audio clip.\n\nDefinitions live in [src/library/sound-effects/index.ts](../../src/library/sound-effects/index.ts). Register your own with \`registerSoundEffect\`.\n\n| id | Name | Category | Length | Params | Description |\n|---|---|---|---|---|---|\n`;
  for (const e of SOUND_EFFECTS) {
    const shape = (e.params as unknown as { shape?: Record<string, z.ZodType> }).shape ?? {};
    const params = Object.entries(shape).map(([k, v]) => `\`${k}\`${v.description ? ` (${v.description})` : ""}`).join(", ");
    out += `| \`${e.id}\` | ${e.name} | ${e.category} | ${e.duration(e.params.parse({}))}s | ${cell(params)} | ${cell(e.description)} |\n`;
  }
  return out;
}

function transitions(): string {
  let out = `${HEADER}# Transitions\n\n${TRANSITIONS.length} transitions between primary-track clips. Set one on the *incoming* clip:\n\n\`\`\`json\n{ "id": "c2", "assetId": "b", "transition": { "type": "slideleft", "duration": 0.4 } }\n\`\`\`\n\nThe transition overlaps the two clips by its duration, which shortens the timeline by that amount. Durations are clamped to fit short clips. All transitions are rendered with FFmpeg \`xfade\`, and audio crossfades at the same time. With Claude, \`set_transition\` with \`sound: true\` adds the sound in the Sound column, peaking in the middle of the transition.\n\n| id | Name | Category | Default duration | Sound | Description |\n|---|---|---|---|---|---|\n`;
  for (const t of TRANSITIONS) out += `| \`${t.id}\` | ${t.name} | ${t.category} | ${t.defaultDuration}s | ${t.sound ? `\`${t.sound}\`` : ""} | ${cell(t.description)}${t.xfade !== t.id ? ` (xfade \`${t.xfade}\`)` : ""} |\n`;
  return out;
}

function animations(): string {
  let out = `${HEADER}# Animations\n\nEntrance (\`animationIn\`) and exit (\`animationOut\`) animations for layers:\n\n\`\`\`json\n{ "type": "text", "text": "Hello", "start": 0, "duration": 3,\n  "animationIn": { "type": "pop", "duration": 0.35, "easing": "ease-out" },\n  "animationOut": { "type": "fade" } }\n\`\`\`\n\nEasing is one of \`linear\`, \`ease-in\`, \`ease-out\` (default) or \`ease-in-out\`. Text and shape layers support every animation (rendered with libass). Media layers support only the ones marked below; any other animation on a media layer falls back to a fade.\n\n| id | Name | Media layers | Default duration | Description |\n|---|---|---|---|---|\n`;
  for (const a of ANIMATIONS) out += `| \`${a.id}\` | ${a.name} | ${a.media ? "yes" : ""} | ${a.defaultDuration}s | ${cell(a.description)} |\n`;
  return out;
}

function captionStyles(): string {
  let out = `${HEADER}# Caption styles\n\n${CAPTION_STYLES.length} caption presets. Captions are generated from asset transcripts and stay in sync through every edit.\n\n\`\`\`json\n"captions": { "style": "bold-pop", "overrides": { "highlightColor": "#00FF88", "position": 0.65 } }\n\`\`\`\n\n**Modes:** \`static\` shows the whole phrase, \`highlight\` colors the spoken word, \`karaoke\` sweeps color across words, \`word\` shows one word at a time, and \`reveal\` shows words as they are spoken. Font sizes assume a 1080px short side and scale with resolution.\n\n## Presets\n\n| id | Name | Mode | Font | Size | Upper | Colors (text / highlight) | Box | Animation | Words/line | Description |\n|---|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const s of CAPTION_STYLES)
    out += `| \`${s.id}\` | ${s.name} | ${s.mode} | ${s.fontFamily} | ${s.fontSize} | ${s.uppercase ? "yes" : ""} | ${s.color} / ${s.highlightColor} | ${s.background ?? ""} | ${s.animation} | ${s.maxWordsPerLine} | ${cell(s.description)} |\n`;
  return out;
}

function captionOverrides(): string {
  const schema = jsonSchema(CaptionStyleSchema.omit({ id: true, name: true, description: true }));
  return `\n## Overridable fields\n\nAny of these can go in \`captions.overrides\`:\n\n${paramTable({ ...schema, required: [] })}`;
}

function components(): string {
  let out = `${HEADER}# Components\n\n${COMPONENTS.length} reusable composite elements. Each one expands into ordinary text, shape or media layers that stay editable afterward, and every created layer is labelled \`component:<id>\`.\n\n\`\`\`ts\naddComponent(project, { component: "lower-third", start: 2, duration: 4, params: { name: "Ada", title: "Engineer" } });\n\`\`\`\n\nWith Claude, use the \`add_component\` tool. Templates use components in their scenes. Register your own with \`registerComponent\`.\n\n## Contents\n\n${COMPONENTS.map((c) => `- [${c.id}](#${slug(c.id)}): ${c.name}`).join("\n")}\n`;
  for (const c of COMPONENTS) out += `\n## ${c.id}\n\n**${c.name}** (${c.category}, default ${c.defaultDuration}s). ${c.description}\n\n${paramTable(jsonSchema(c.params))}`;
  return out;
}

function templates(): string {
  const cats = [...new Set(TEMPLATES.map((t) => t.category))];
  let out = `${HEADER}# Templates\n\n${TEMPLATES.length} built-in templates. Each one is a JSON spec with inputs (slots), a look (theme, captions, grade, transitions) and an ordered list of scenes, plus guidance on how to edit footage to match it. See the [templates guide](../guides/templates.md) to write your own.\n\n\`\`\`ts\nconst { project, warnings } = await applyTemplate("podcast-clip", { main: "ep12.mp4", title: "Why most startups fail" }, { probe });\n\`\`\`\n\n## Contents\n\n| id | Name | Format | Length | Category |\n|---|---|---|---|---|\n`;
  for (const t of TEMPLATES) out += `| [\`${t.id}\`](#${slug(t.id)}) | ${t.name} | ${t.aspectRatio} | ${t.idealDuration[0]}-${t.idealDuration[1]}s | ${t.category} |\n`;
  for (const c of cats) {
    out += `\n## ${c[0]!.toUpperCase()}${c.slice(1)}\n`;
    for (const t of TEMPLATES.filter((x) => x.category === c)) {
      out += `\n### ${t.id}\n\n**${t.name}**: ${t.description}\n\n`;
      out += `- **Format:** ${t.aspectRatio} at ${t.fps}fps, ideally ${t.idealDuration[0]}-${t.idealDuration[1]}s\n`;
      if (t.platforms.length) out += `- **Platforms:** ${t.platforms.join(", ")}\n`;
      out += `- **Look:** captions ${t.captions ? `\`${t.captions.style}\`` : "none"}, transition ${t.transition ? `\`${t.transition.type}\`` : "hard cut"}, grade ${t.grade.length ? t.grade.map((g) => `\`${g.type}\``).join(" + ") : "none"}, fonts ${t.theme.headingFont} / ${t.theme.fontFamily}\n`;
      if (t.tags.length) out += `- **Tags:** ${t.tags.join(", ")}\n`;
      out += `\n**Editing guidance:** ${t.aiGuidance}\n\n**Inputs**\n\n| Slot | Kind | Required | Description |\n|---|---|---|---|\n`;
      for (const s of t.slots) {
        const fields = s.fields ? ` Fields: ${Object.entries(s.fields).map(([k, v]) => `\`${k}\` (${v})`).join(", ")}.` : "";
        out += `| \`${s.id}\` | ${s.kind} | ${s.required ? "yes" : ""} | ${cell(s.description + fields)} |\n`;
      }
      out += `\n**Scenes**\n\n`;
      for (const sc of t.scenes) {
        const len = sc.fitMedia ? `follows media${sc.maxDuration ? ` (max ${sc.maxDuration}s)` : ""}` : sc.durationFrom ? `from ${sc.durationFrom}, else ${sc.duration}s` : `${sc.duration}s`;
        out += `${t.scenes.indexOf(sc) + 1}. **${sc.name}**${sc.repeat ? ` (repeats for each \`${sc.repeat}\`)` : ""}${sc.optional ? " _(optional)_" : ""}: ${sc.purpose}. Length: ${len}.\n`;
      }
    }
  }
  return out;
}

export async function generateDocs(): Promise<Record<string, string>> {
  return {
    "claude-tools.md": claudeTools(),
    "effects.md": effects(),
    "audio-effects.md": audioEffects(),
    "sound-effects.md": soundEffects(),
    "transitions.md": transitions(),
    "animations.md": animations(),
    "caption-styles.md": captionStyles() + captionOverrides(),
    "components.md": components(),
    "templates.md": templates(),
  };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const files = await generateDocs();
  await mkdir(REFERENCE_DIR, { recursive: true });
  let stale = 0;
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(REFERENCE_DIR, name);
    const current = await readFile(file, "utf8").catch(() => "");
    if (current === content) continue;
    if (check) {
      console.error(`out of date: docs/reference/${name}`);
      stale++;
    } else {
      await writeFile(file, content, "utf8");
      console.log(`wrote docs/reference/${name}`);
    }
  }
  if (check && stale) {
    console.error("Run `npm run docs` to regenerate.");
    process.exit(1);
  }
}
